/// Width in pixels of `text` at `scale` (6 px per character, one of them spacing).
pub fn width(text: &str, scale: usize) -> usize {
    (text.chars().count() * 6).saturating_sub(1) * scale
}

/// Draws `text` with its top-left at (x, y) into an RGBA image, on a light box for legibility.
pub fn draw(rgba: &mut [u8], w: usize, h: usize, x: i64, y: i64, text: &str, scale: usize, color: [u8; 3]) {
    let (tw, th) = (width(text, scale) as i64, 7 * scale as i64);
    let mut put = |px: i64, py: i64, c: [u8; 3]| {
        if px >= 0 && py >= 0 && (px as usize) < w && (py as usize) < h {
            let i = (py as usize * w + px as usize) * 4;
            rgba[i..i + 3].copy_from_slice(&c);
            rgba[i + 3] = 255;
        }
    };
    let m = scale as i64;
    for py in y - m..y + th + m {
        for px in x - m..x + tw + m {
            put(px, py, [255, 255, 255]);
        }
    }
    for (k, ch) in text.chars().enumerate() {
        let g = glyph(ch);
        for (row, bits) in g.iter().enumerate() {
            for col in 0..5 {
                if bits & (1 << (4 - col)) != 0 {
                    for dy in 0..m {
                        for dx in 0..m {
                            put(x + (k as i64 * 6 + col) * m + dx, y + row as i64 * m + dy, color);
                        }
                    }
                }
            }
        }
    }
}
